import { describe, expect, it } from 'vitest'
import { generate, generateFrameRaw } from '../src/core/gcode/generate'
import { parseGcode } from '../src/core/gcode/preview'
import { buildResume } from '../src/core/gcode/resume'
import { GrblClient, isSyncLine } from '../src/core/grbl/client'
import { FALCON2_12W, defaultLayer, type LayerJob } from '../src/core/types'

const square = (x: number, y: number, s = 10) => ({ closed: true, points: [{ x, y }, { x: x + s, y }, { x: x + s, y: y + s }, { x, y: y + s }] })
const job = (o: Partial<ReturnType<typeof defaultLayer>>, vectors = [square(20, 20)]): LayerJob => ({ settings: { ...defaultLayer('a', 'A', '#f00'), ...o }, vectors, images: [] })

describe('G-code follows GRBL laser-mode rules', () => {
  const out = generate([job({ mode: 'line', speed: 10, power: 50 }), job({ mode: 'fill', speed: 60, power: 30 }, [square(50, 50, 20)])], { machine: FALCON2_12W, origin: { mode: 'job', anchor: 'bl' }, returnToOrigin: true, constantPower: false })
  const motion = out.lines.filter((l) => /^(G[01]|X|Y)/.test(l))

  it('starts with units, absolute mode and dynamic power (M4), laser at S0', () => {
    expect(out.lines.slice(0, 3)).toEqual(['; Generated by Ember Laser Studio', 'G21 G90 G17 G94', 'M4 S0'])
  })
  it('the first move is a rapid (G0), so nothing burns on the way from wherever the head is', () => {
    expect(motion[0]).toMatch(/^G0 X/)
  })
  it('every G1 has a feed rate before it, ends laser off and returns home', () => {
    const firstG1 = out.lines.findIndex((l) => l.startsWith('G1'))
    expect(out.lines[firstG1]).toMatch(/F\d+/)
    expect(out.lines.slice(-2)).toEqual(['M5 S0', 'G0 X0 Y0'])
  })
  it('all lines fit GRBL limits after cleaning', () => {
    expect(() => GrblClient.prepareJob(out.lines)).not.toThrow()
  })
  it('burns only on feed moves', () => {
    const p = parseGcode(out.lines)
    expect(p.moves.filter((m) => m.rapid && m.s > 0)).toEqual([])
    expect(p.moves.filter((m) => !m.rapid && m.s > 0).length).toBeGreaterThan(10)
  })
})

describe('bed checks use the real tool path', () => {
  it('warns when overscan would run off the bed even though the artwork fits', () => {
    const out = generate([job({ mode: 'fill', speed: 60, power: 30, overscan: 3 }, [square(0, 50, 20)])], { machine: FALCON2_12W, origin: { mode: 'bed' }, returnToOrigin: false, constantPower: false })
    expect(out.warnings.join(' ')).toMatch(/overscan/)
  })
  it('is quiet when everything fits', () => {
    const out = generate([job({ mode: 'fill', speed: 60, power: 30 }, [square(50, 50, 20)])], { machine: FALCON2_12W, origin: { mode: 'bed' }, returnToOrigin: false, constantPower: false })
    expect(out.warnings).toEqual([])
  })
})

describe('framing and resume', () => {
  it('frames imported G-code in its own coordinates (no flip)', () => {
    const f = generateFrameRaw({ minX: 0, minY: 0, maxX: 30, maxY: 20 })
    expect(f).toContain('G0 X0 Y0')
    expect(f).toContain('G1 X30 Y20 S0 F6000')
  })
  it('resume never replays "set origin here"', () => {
    const lines = ['G10L20P1X0Y0', 'G54', 'M4S0', 'G0X1Y1', 'G1X5S500F600', 'G1X9']
    expect(buildResume(lines, 0).some((l) => /G10/.test(l))).toBe(false)
  })
  it('EEPROM-writing lines are recognised', () => {
    for (const l of ['G10L20P1X0Y0', 'G10 L2 P1 X0 Y0', '$32=1', '$H', 'G28.1']) expect(isSyncLine(l)).toBe(true)
    for (const l of ['G1X10', 'G0X1Y1', 'M4S0', 'G1 X100 S10']) expect(isSyncLine(l)).toBe(false)
  })
})
